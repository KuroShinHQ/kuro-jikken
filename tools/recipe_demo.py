def dir_html(rel: str) -> str:
    folder = (ROOT / rel).resolve()
    rows = []
    if folder != ROOT:
        rows.append('<li><a href="../">../</a></li>')
    for child in sorted(folder.iterdir(), key=lambda p: (p.is_file(), p.name.lower())):
        if child.name.startswith("."):
            continue
        name = child.name + ("/" if child.is_dir() else "")
        rows.append(f'<li><a href="{urllib.parse.quote(name)}">{html.escape(name)}</a></li>')
    title = "/" + rel.strip("/") + "/"
    return f"""<!doctype html><html lang="tr"><head><meta charset="utf-8">
<title>{html.escape(title)}</title><style>
body{{margin:0;background:#0d1014;color:#e8e6e1;font:15px/1.6 Inter,system-ui,sans-serif}}
main{{max-width:900px;margin:0 auto;padding:48px 24px}}
h1{{font:500 30px/1.2 "Instrument Serif",Georgia,serif;margin:0 0 6px}}
p{{color:#7d7870;font-size:13px;margin:0 0 22px}}
ul{{list-style:none;padding:0;margin:0;border-top:1px solid #232a31}}
li{{border-bottom:1px solid #1b2127}}
a{{display:block;padding:11px 6px;color:#cfe3d8;text-decoration:none;font:500 13.5px/1.4 "JetBrains Mono",monospace}}
a:hover{{background:#12171c;color:#fff}}
</style></head><body><main>
<h1>{html.escape(title)}</h1><p>kuro-jikken · statik dosya listesi</p>
<ul>{''.join(rows)}</ul></main></body></html>"""


class Handler(SimpleHTTPRequestHandler):
    rows = []

    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(ROOT), **kwargs)

    def do_GET(self):  # noqa: N802 - http.server API
        if self.path in ("/", "/index.html"):
            body = index_html(self.rows).encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(body)
            return
        if self.path == "/api/recipes":
            payload = [{
                "id": row["doc"]["id"],
                "title": row["doc"]["title"],
                "kind": row["doc"]["kind"],
                "verdict": row["verdict"],
                "steps": row["steps"],
                "sources": row["sources"],
                "page": row["page_url"],
            } for row in self.rows]
            body = json.dumps(payload, ensure_ascii=False, indent=1).encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(body)
            return
        if self.path.endswith("/"):
            rel = urllib.parse.unquote(self.path).strip("/")
            if (ROOT / rel).is_dir():
                body = dir_html(rel).encode("utf-8")
                self.send_response(200)
                self.send_header("Content-Type", "text/html; charset=utf-8")
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)
                return
        super().do_GET()

    def log_message(self, *args):  # keep the console for the summary
        pass


def check(rows: list) -> int:
    problems = 0
    for row in rows:
        page = row["page"]
        stale = not page.is_file()
        if not stale:
            built = recipe_page.generate(row["path"], LABS, check=True)
            stale = built["stale"]
        state = "OK" if row["verdict"] == "PASS" and not stale else "FAIL"
        problems += state == "FAIL"
        print(f"{state:4} {row['doc']['id']:26} verdict={row['verdict']:4} "
              f"steps={row['steps']} sources={row['sources']} "
              f"page={'stale' if stale else 'fresh'} {page.name}")
    print(f"{len(rows) - problems}/{len(rows)} recipes ready")
    return 1 if problems else 0


def main() -> int:
    parser = argparse.ArgumentParser(description="serve the two gated recipe pages")
    parser.add_argument("--check", action="store_true", help="gate + page freshness only")
    parser.add_argument("--no-open", action="store_true", help="do not open a browser")
    parser.add_argument("--port", type=int, default=0, help="0 = pick a free port")
    args = parser.parse_args()

    rows = collect()
    if args.check:
        return check(rows)

    Handler.rows = rows
    server = ThreadingHTTPServer(("127.0.0.1", args.port), Handler)
    url = f"http://127.0.0.1:{server.server_address[1]}/"
    print(f"serving {ROOT}")
    print(f"open {url}")
    for row in rows:
        print(f"  {row['doc']['id']:26} {row['verdict']:4} {url}{row['page_url']}")
    if not args.no_open:
        threading.Timer(0.4, lambda: webbrowser.open(url)).start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nstopped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
