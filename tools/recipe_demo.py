"""Open the two gated recipe pages in a browser, from one command.

    python tools/recipe_demo.py              # serve + open the browser
    python tools/recipe_demo.py --no-open    # serve only (prints the URLs)
    python tools/recipe_demo.py --check      # gate + page freshness, no server

The pages are generated by ``tools/recipe_page.py`` and live under the lab
skill. They load three.js from a CDN, so the browser needs network; everything
else (kit, recipe copy, sources) is served from this repository.

This is a viewer, not an engine: the numbers on the pages are the gated recipe
document's own numbers, and the pages say what the recipe does not claim.
"""
import argparse
import html
import json
import pathlib
import sys
import threading
import urllib.parse
import webbrowser
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "mcp"))
sys.path.insert(0, str(ROOT / "tools"))

import recipe  # noqa: E402
import recipe_page  # noqa: E402

RECIPES = sorted((ROOT / "data" / "recipes").glob("*.json"))
LABS = ROOT / ".opencode" / "skills" / "lab" / "labs"


def collect() -> list:
    rows = []
    for path in RECIPES:
        doc = recipe.load(path)
        verdict = recipe.validate(doc)
        page = LABS / recipe_page.page_name(path)
        rows.append({
            "path": path,
            "doc": doc,
            "verdict": verdict["verdict"],
            "page": page,
            "page_url": page.relative_to(ROOT).as_posix(),
            "steps": len(doc["steps"]),
            "ingredients": len(doc["ingredients"]),
            "sources": len(verdict["sources"]),
            "claim_boundary": doc["claim_boundary"],
        })
    return rows


